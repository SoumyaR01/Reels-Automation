"""Section 7 Reel Plan Schema representing structured timeline and editing instructions."""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class ReelRequest(BaseModel):
    """User intent and constraints specification."""

    theme: str = "motivation"
    emotion: str = "hopeful"
    target_duration_seconds: float = 30.0
    aspect_ratio: str = "9:16"
    dialogue_preference: str = "optional"  # required, optional, none


class SelectedClip(BaseModel):
    """A single source clip segment scheduled on the reel timeline."""

    movie_id: str
    scene_id: str
    source_start_seconds: float
    source_end_seconds: float
    reel_start_seconds: float
    reel_end_seconds: float
    reason: str


class TimedCaption(BaseModel):
    """A timed on-screen subtitle or quote caption."""

    start_seconds: float
    end_seconds: float
    text: str
    speaker: Optional[str] = None
    style: str = "default"  # default, emphasis, quote


class HindiShayari(BaseModel):
    """Original AI-generated Hindi shayari strictly marked with ai_generated guardrails."""

    language: str = "hi"
    text: str
    ai_generated: bool = True
    placement: str = "overlay_or_voiceover"
    reel_start_seconds: float = 22.0
    reel_end_seconds: float = 30.0


class RenderSettings(BaseModel):
    """Output rendering parameters."""

    width: int = 1080
    height: int = 1920
    fps: int = 30
    crf: int = 20
    preset: str = "medium"


class ReelPlan(BaseModel):
    """Section 7 Structured Reel Plan generated by Reel Planning Agent."""

    plan_id: str = "plan_001"
    title: str = "Untitled Reel"
    request: ReelRequest = Field(default_factory=ReelRequest)
    selected_clips: List[SelectedClip] = Field(default_factory=list)
    captions: List[TimedCaption] = Field(default_factory=list)
    shayari: Optional[HindiShayari] = None
    effects: List[str] = Field(default_factory=list)
    music_direction: str = "Instrumental, gradual build, emotional payoff"
    transition_notes: List[str] = Field(default_factory=list)
    render_settings: RenderSettings = Field(default_factory=RenderSettings)
    approved_by_user: bool = False
